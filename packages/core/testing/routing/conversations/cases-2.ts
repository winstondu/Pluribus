import type { CorpusTopic } from '../corpus/types'
import { SCENES, SCENE_DOMAIN, type SceneName } from './scenes'
import type { Behavior, ConversationCase, Register, Role } from './types'

/**
 * More cases of the conversation corpus, concatenated into
 * `CONVERSATION_CORPUS` by `cases.ts`: every behavior to at least six
 * cases, more contrast families and traps, the conversation shapes of
 * `scenes-2.ts`, and prompts in French, German and Portuguese, some of them
 * switching language inside one prompt.
 *
 * Where a family name ends in a number, the number means nothing but this:
 * `partitionOf` holds out every third family of a behavior in the order of
 * their names' hashes, so a family that sorted among those of `cases.ts`
 * would move earlier cases across the tuning boundary, and cases already
 * tuned on would be scored as held out. With the number, every family here
 * sorts after every family of its behavior there, and no earlier case
 * changes side.
 */

/** The routing-corpus topics a behavior is reported under, as in `cases.ts`. */
const TOPICS: { readonly [B in Behavior]: readonly CorpusTopic[] } = {
  'new-chain': ['placement'],
  continue: ['targets', 'placement'],
  branch: ['targets', 'placement'],
  fork: ['placement', 'dependencies'],
  wait: ['dependencies'],
  'wait-group': ['dependencies', 'placement'],
  'join-back': ['placement', 'targets'],
  'join-chain': ['placement', 'targets'],
  'join-lines': ['targets', 'placement'],
  'ask-target': ['targets'],
  'revise-work': ['revision'],
  'revise-shared': ['revision', 'requirements'],
  'answer-question': ['targets', 'clarification'],
  clarify: ['clarification'],
  'split-independent': ['splits'],
  'split-sequential': ['splits', 'dependencies'],
  'keep-atomic': ['splits'],
  'session-requirement': ['requirements'],
}

type Draft = Omit<ConversationCase, 'scene' | 'covers' | 'family' | 'domain' | 'role' | 'register'> & {
  readonly in: SceneName
  readonly family?: string
  /** Default `canonical`. */
  readonly role?: Role
  /** Default `plain`. */
  readonly register?: Register
}

function define(drafts: readonly Draft[]): ConversationCase[] {
  return drafts.map(({ in: name, family, role, register, ...rest }) => ({
    ...rest,
    scene: SCENES[name],
    covers: TOPICS[rest.behavior],
    family: family ?? rest.id,
    role: role ?? 'canonical',
    register: register ?? 'plain',
    domain: SCENE_DOMAIN[name],
  }))
}

